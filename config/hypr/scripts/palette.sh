}

# ensure_targets — файлы на месте, чтобы импорт не падал на отсутствующем
# include, даже если генератор ничего не записал.
ensure_targets() {
    ensure_target_dirs
    local f
    for f in "${TARGETS[@]}"; do
        [ -e "$f" ] || : >"$f"
    done
}

# generate_palette <image> — режим dynamic: палитра из обоев. Генерацию
# делегируем внешнему генератору (wallust) с его конфигом шаблонов; при сбое
# пробуем сохранённые обои, но не валим вызывающего — targets остаются
# пригодными для импорта.
generate_palette() {
    local image="$1"
    # Сначала обнуляем цели: сбой генерации оставит их пустыми (импортируемыми),
    # а не с содержимым прошлого режима — light и dynamic не могут сосуществовать.
    clear_targets
    if command -v wallust >/dev/null 2>&1; then
        # Один прогон, если обои те же: не гоняем генератор дважды за один вызов.
        if [ "$image" = "$WALLPAPER" ]; then
            wallust run "$image" || true
        else
            wallust run "$image" || wallust run "$WALLPAPER" || true
        fi
    fi
    ensure_targets
}

# materialise_mode <mode> [image] — единственный путь и проверки, и раздачи
# режима: неизвестный режим отсекается здесь же.
materialise_mode() {
    case "${1:-}" in
        dark) clear_targets ;;
        light) write_light ;;
        dynamic) generate_palette "${2:-$WALLPAPER}" ;;
        *) usage ;;
    esac
}

# persist_mode <mode> — записать единственное значение режима. Запись режима
# структурно вытесняет прочие представления: старые маркеры удаляются, так что
# light и dynamic не могут сосуществовать.
persist_mode() {
    mkdir -p "$(dirname "$MODE_FILE")"
    printf '%s\n' "$1" >"$MODE_FILE"
    rm -f "$LEGACY_LIGHT" "$LEGACY_DYNAMIC"
}

set_mode() { # set_mode <dark|light|dynamic> [image]
    materialise_mode "$1" "${2:-}"
    persist_mode "$1"
    reload
}

# apply_mode [image] — применить текущий режим, не меняя его.
apply_mode() {
    materialise_mode "$(current_mode)" "${1:-}"
    reload
}

toggle_mode() {
    if [ "$(current_mode)" = light ]; then
        set_mode dark
    else
        set_mode light
    fi
}

main() {
    case "${1:-}" in
        status) current_mode ;;
        set) set_mode "${2:-}" "${3:-}" ;;
        toggle) toggle_mode ;;
        apply) apply_mode "${2:-}" ;;
        clear) set_mode dark ;;
        *) usage ;;
    esac
}

main "$@"
