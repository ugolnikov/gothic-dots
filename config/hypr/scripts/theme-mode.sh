#!/usr/bin/env bash
# theme-mode.sh — быстрое переключение готической палитры: тёмная ⇄ светлая.
#   theme-mode.sh dark | light | toggle | status
#
# Палитра пишется в те же файлы *.dynamic.*, что и wallust, — приложения уже
# их импортируют. «dark» просто очищает их, возвращая фиксированную готику.
# Поэтому light-режим и палитра из обоев (dynamic-theme) взаимоисключающие:
# включение light снимает маркер dynamic-theme.
#
# Покрыто: Hyprland, Waybar, rofi, kitty, swaync. foot/mako/tofi/hyprlock и GTK
# остаются на своей фиксированной палитре (см. README).
set -euo pipefail

CONFIG="${XDG_CONFIG_HOME:-$HOME/.config}"
MARKER="$CONFIG/hypr/light-theme"

HYPR="$CONFIG/hypr/conf.d/colors.dynamic.conf"
WAYBAR="$CONFIG/waybar/colors.dynamic.css"
ROFI="$CONFIG/rofi/colors.dynamic.rasi"
KITTY="$CONFIG/kitty/colors.dynamic.conf"
SWAYNC="$CONFIG/swaync/colors.dynamic.css"

reload() {
    hyprctl reload >/dev/null 2>&1 || true
    pkill -SIGUSR2 -x waybar 2>/dev/null || true
    swaync-client --reload-css >/dev/null 2>&1 || true
}

clear_dynamic() {
    for f in "$HYPR" "$WAYBAR" "$ROFI" "$KITTY" "$SWAYNC"; do
        mkdir -p "$(dirname "$f")"
        : >"$f"
    done
}

write_light() {
    mkdir -p "$(dirname "$HYPR")" "$(dirname "$WAYBAR")" "$(dirname "$ROFI")" \
        "$(dirname "$KITTY")" "$(dirname "$SWAYNC")"

    cat >"$HYPR" <<'EOF'
# light theme — generated by theme-mode.sh, do not edit
general {
    col.active_border = rgba(8c1220ff)
    col.inactive_border = rgba(c7bfaaff)
}
misc {
    background_color = rgba(f2efe7ff)
}
EOF

    cat >"$WAYBAR" <<'EOF'
/* light theme — generated by theme-mode.sh, do not edit */
@define-color base     #f2efe7;
@define-color mantle   #e7e2d6;
@define-color crust    #dcd6c8;
@define-color surface0 #e2dccf;
@define-color surface1 #c7bfaa;
@define-color overlay0 #8b857c;
@define-color text     #2a2723;
@define-color subtext  #6f6a62;
@define-color blue     #5a3f7a;
@define-color lavender #5a3f7a;
@define-color mauve    #8c1220;
@define-color green    #7a6638;
@define-color yellow   #7a6638;
@define-color peach    #7a6638;
@define-color red      #8c1220;
@define-color teal     #5a3f7a;
EOF

    cat >"$ROFI" <<'EOF'
/* light theme — generated by theme-mode.sh, do not edit */
* {
    base:      #f2efe7;
    mantle:    #e7e2d6;
    crust:     #dcd6c8;
    surface0:  #e2dccf;
    surface1:  #c7bfaa;
    overlay0:  #8b857c;
    text:      #2a2723;
    subtext:   #6f6a62;
    blue:      #5a3f7a;
    lavender:  #5a3f7a;
    sapphire:  #5a3f7a;
    green:     #7a6638;
    yellow:    #7a6638;
    peach:     #7a6638;
    red:       #8c1220;
    mauve:     #8c1220;
    pink:      #8b5a63;
}
EOF

    cat >"$KITTY" <<'EOF'
# light theme — generated by theme-mode.sh, do not edit
foreground              #2a2723
background              #f2efe7
selection_foreground    #f2efe7
selection_background    #8c1220
cursor                  #8c1220
cursor_text_color       #f2efe7
url_color               #5a3f7a

active_border_color     #8c1220
inactive_border_color   #c7bfaa
active_tab_background   #8c1220
active_tab_foreground   #f2efe7
inactive_tab_background #e7e2d6
inactive_tab_foreground #6f6a62
tab_bar_background      #dcd6c8

color0  #2a2723
color8  #6f6a62
color1  #8c1220
color9  #b3162b
color2  #5f6b3f
color10 #7a6638
color3  #8a6d2f
color11 #a8823a
color4  #5a3f7a
color12 #6c4f8f
color5  #7a4a55
color13 #96606c
color6  #356a6a
color14 #4a8888
color7  #4a453d
color15 #2a2723
EOF

    cat >"$SWAYNC" <<'EOF'
/* light theme — generated by theme-mode.sh, do not edit */
@define-color base     #f2efe7;
@define-color mantle   #e7e2d6;
@define-color surface0 #e2dccf;
@define-color overlay0 #8b857c;
@define-color text     #2a2723;
@define-color subtext  #6f6a62;
@define-color blue     #5a3f7a;
@define-color mauve    #8c1220;
@define-color green    #7a6638;
@define-color yellow   #7a6638;
@define-color peach    #7a6638;
@define-color red      #8c1220;
EOF
}

status() {
    if [ -e "$MARKER" ]; then echo light; else echo dark; fi
}

current() { status; }

apply_light() {
    # Светлая палитра и палитра из обоев (wallust) делят одни файлы, поэтому
    # включая light, снимаем маркер dynamic-theme — иначе theme.sh при следующем
    # логине снова прогонит wallust и перетрёт светлую палитру.
    rm -f "$CONFIG/hypr/dynamic-theme"
    write_light
    : >"$MARKER"
    reload
}
apply_dark() {
    clear_dynamic
    rm -f "$MARKER"
    reload
}

case "${1:-toggle}" in
    dark) apply_dark ;;
    light) apply_light ;;
    toggle) if [ "$(current)" = light ]; then apply_dark; else apply_light; fi ;;
    status) status ;;
    *)
        echo "usage: theme-mode.sh [dark|light|toggle|status]" >&2
        exit 1
        ;;
esac

notify-send "Тема" "$([ "$(status)" = light ] && echo 'светлая' || echo 'готика (тёмная)')" 2>/dev/null || true
